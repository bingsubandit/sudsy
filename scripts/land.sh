#!/usr/bin/env bash
# Lands a finished step on origin/main after a passing `finish.sh` (CLAUDE.md "Getting onto
# origin/main"): scripts/land.sh MESSAGE-FILE
#  1. squash: when origin/main is still the merge-base (no fetch moved it since the branch was cut),
#     `git reset --soft <merge-base>`, add everything (the `bench/history.jsonl` line included) and
#     commit with `-F MESSAGE-FILE`. After a fetch the merge-base is no longer origin/main, so a squash
#     is refused (rebase first; then it is one again); a single clean commit is landed as it is.
#  2. fetch + `git rebase origin/main`. Conflicts: `bench/history.jsonl` keeps both sides (markers
#     removed); `docs/ai/kit/index.md` and `docs/ai/design/single-use.txt` are regenerated by
#     `cargo xtask codegen`; any other file stops the script for a hand merge (resolve, `git add`,
#     `git rebase --continue`, run land.sh again). No `--ours`/`--theirs`, no reset after a fetch.
#  3. refuse when a conflict marker is left; run `codegen --check`, `dupes --check`,
#     `cost.sh --languages --check origin/main HEAD` and the HARD RULE review below (LAND_CHECKS
#     replaces them, for tests).
#  4. print `git show --stat HEAD` and `git diff origin/main --stat`, push `HEAD:main`. A rejected
#     push repeats 2-4 with a new fetch, at most 3 rounds.
set -uo pipefail
cd "$(dirname "$0")/.."
. scripts/lib/slot.sh
msg=${1:-}
[ -f "$msg" ] || { echo "LAND FAILED: usage: scripts/land.sh MESSAGE-FILE"; exit 1; }
die() { echo "LAND FAILED: $*"; exit 1; }
[ -z "$(git ls-files -u)" ] || die "unmerged files: resolve them, git add, git rebase --continue, run again"
[ ! -d "$(git rev-parse --git-path rebase-merge)" ] || die "a rebase is in progress: git rebase --continue (or --abort), run again"

# --- 1. one commit ----------------------------------------------------------------------------------
base=$(git merge-base HEAD origin/main) || die "no merge-base with origin/main"
dirty=$(git status --porcelain --untracked-files=normal | head -1)
ahead=$(git rev-list --count "$base..HEAD")
if [ "$(git rev-parse origin/main)" = "$base" ]; then
  [ -n "$dirty" ] || [ "$ahead" -gt 0 ] || die "nothing to land"
  git reset --soft "$base" && git add -A && git commit -q -F "$msg" || die "commit"
elif [ -z "$dirty" ] && [ "$ahead" -eq 1 ]; then
  echo "land: origin/main is ahead of the merge-base (a fetch happened); landing the single commit as it is"
else
  die "origin/main is ahead of the merge-base $(git rev-parse --short "$base") (a fetch happened): a squash reset would drop what the fetch brought. Commit, then git rebase origin/main, then run again"
fi

# --- 2. rebase, resolving the known conflicts -------------------------------------------------------
resolve() { # after a conflicting rebase step: 0 when all conflicts are resolved and staged
  local f other= gen=
  for f in $(git diff --name-only --diff-filter=U); do
    case "$f" in
      bench/history.jsonl) sed -i -e '/^<<<<<<< /d' -e '/^=======$/d' -e '/^>>>>>>> /d' "$f"; git add -- "$f" ;;
      docs/ai/kit/index.md|docs/ai/design/single-use.txt) gen="$gen $f" ;;
      *) other="$other $f" ;;
    esac
  done
  [ -z "$other" ] || { echo "LAND STOPPED: hand merge needed:$other"; echo "resolve, git add, git rebase --continue, then run scripts/land.sh again"; return 1; }
  if [ -n "$(git diff --name-only --diff-filter=U)" ]; then
    cargo xtask codegen || { echo "LAND STOPPED: cargo xtask codegen failed"; return 1; }
    git add -- $gen
  fi
  [ -z "$(git diff --name-only --diff-filter=U)" ]
}
rebase() {
  git fetch -q origin main || die "fetch"
  local rounds=0
  git rebase origin/main >/dev/null 2>&1 && return 0
  while [ -d "$(git rev-parse --git-path rebase-merge)" ]; do
    rounds=$((rounds + 1)); [ $rounds -le 20 ] || die "rebase does not finish"
    resolve || exit 1
    GIT_EDITOR=true git rebase --continue >/dev/null 2>&1
  done
}

# HARD RULE review: when the change adds lines to a language crate, a fresh headless Claude call
# (scripts/review-hard-rule.md, read-only tools, structured output) sorts each added item into OK or
# MECHANISM; a mechanism refuses the landing. Its output goes to .cargo/tmp/review.txt and, for the
# lead, to hard-rule-reviews.log in the common git dir. The verdict is kept per content (the commit
# message and the diff without line numbers): the model is not deterministic on borderline items, so
# the same change is never reviewed twice and a FAIL cannot be rerun into a PASS; a changed diff or
# message (a fix, a Language-only or Lead-approved line) gets a new review.
review() {
  local d out json key log verdicts prev
  d=$(git diff origin/main HEAD -- 'crates/lang-*')
  grep -q '^+[^+]' <<<"$d" || return 0
  key=$({ git log -1 --format=%B HEAD; grep -v -e '^@@' -e '^index ' <<<"$d"; } | sha256sum | cut -c1-16)
  log="$(git rev-parse --git-common-dir)/hard-rule-reviews.log"
  verdicts="$(git rev-parse --git-common-dir)/hard-rule-verdicts"
  prev=$(grep "^$key " "$verdicts" 2>/dev/null | tail -1 | cut -d' ' -f2)
  [ "$prev" = PASS ] && return 0
  [ "$prev" = FAIL ] && { echo "LAND FAILED: HARD RULE review already failed this exact change (.cargo/tmp/review.txt); change the code, or escalate to the lead"; return 1; }
  mkdir -p .cargo/tmp
  # One call on the API credit (scripts/haiku.py: SUDSY_API_KEY, no fallback), structured output; the verdict comes from the list.
  json=$({ git log -1 --format=%B HEAD; echo; echo '--- diff'; echo "$d"; } |
    python3 scripts/haiku.py --schema scripts/review-hard-rule.schema.json --system scripts/review-hard-rule.md \
      --tools "Read Grep Glob" --budget 1 "Review the change on stdin." 2>.cargo/tmp/review.err)
  [ -n "$json" ] || { echo "LAND FAILED: HARD RULE review call failed: $(cat .cargo/tmp/review.err)"; return 1; }
  out=$(jq -r '(.findings[] | "\(.file):\(.function) | \(.class) | \(.reason)"), (if ([.findings[] | select(.class == "MECHANISM")] | length) == 0 then "VERDICT: PASS" else "VERDICT: FAIL (\([.findings[] | select(.class == "MECHANISM")] | length) mechanisms)" end)' <<<"$json" 2>&1)
  mkdir -p .cargo/tmp; echo "$out" >.cargo/tmp/review.txt
  { echo "== $(date -u +%FT%TZ) $(git rev-parse --abbrev-ref HEAD) $(git log -1 --format=%s HEAD)"; echo "$out"; } >>"$log"
  if grep -q '^VERDICT: PASS' <<<"$out"; then echo "$key PASS" >>"$verdicts"; return 0; fi
  grep -q '^VERDICT: FAIL' <<<"$out" || { echo "LAND FAILED: HARD RULE review gave no verdict (.cargo/tmp/review.txt)"; return 1; }
  echo "$key FAIL" >>"$verdicts"
  echo "$out" | grep '| MECHANISM |'
  echo "LAND FAILED: HARD RULE review: move each MECHANISM above into a shared crate (or name a real fact in a Language-only: line), amend, run again; a finding you hold to be wrong goes to the lead"
  return 1
}

attempt=0
while [ $attempt -lt 3 ]; do
  attempt=$((attempt + 1))
  rebase
  # --- 3. markers and checks ------------------------------------------------------------------------
  marked=$(git diff --name-only origin/main HEAD | xargs -r grep -lE '^(<<<<<<<|>>>>>>>) ' 2>/dev/null)
  [ -z "$marked" ] || die "conflict markers left in: $marked"
  git ls-tree HEAD .cargo/tmp/.gitkeep | grep -q . || die "HEAD has no .cargo/tmp/.gitkeep: git checkout origin/main -- .cargo/tmp/.gitkeep; git add -f it; git commit --amend --no-edit"
  if [ -n "${LAND_CHECKS:-}" ]; then
    bash -c "$LAND_CHECKS" || die "checks (LAND_CHECKS)"
  else
    cargo xtask codegen --check || die "codegen --check"
    cargo xtask dupes --check || die "dupes --check"
    scripts/cost.sh --languages --check origin/main HEAD || die "cost.sh --languages --check (add a Language-only: or Cost-exception: line to the commit message and git commit --amend)"
    # Presets are pure config (CLAUDE.md): formatter and rule code never compares a preset name.
    presets=$(git diff origin/main HEAD -- 'crates/core-*/src' 'crates/lang-*/src' ':!crates/core-config' |
      grep -E '^\+[^+]' | grep -vE '^\+\s*//' | grep -i 'preset' | grep -E '==|!=|matches!|starts_with|contains\(|match ')
    [ -z "$presets" ] || die "code compares a preset name (presets are pure config; make the difference a named option):
$presets"
    review || exit 1
  fi
  # --- 4. look and push -----------------------------------------------------------------------------
  git show --stat HEAD
  git diff origin/main --stat
  if git push -q origin HEAD:main; then echo "LAND OK: $(git rev-parse --short HEAD) on origin/main"; exit 0; fi
  echo "land: push rejected (attempt $attempt of 3); fetching again"
done
die "push rejected 3 times"
